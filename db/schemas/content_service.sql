-- База Content Service (content_db). Таблицы — по services/ENDPOINTS.md: posts,
-- post_images, post_likes, reposts, post_favorites, hidden_posts, comments,
-- comment_likes, post_reports.
-- Исходник: social_network_db/init/01_schema.sql. Отличие одно: users живут в
-- другой базе, поэтому author_id / user_id / reporter_id — просто id пользователя
-- без внешнего ключа. user_replicas и follow_replicas — локальная копия нужных
-- данных User Service, её наполняют события из RabbitMQ. Событие user.deleted
-- удаляет весь контент пользователя.

CREATE TABLE IF NOT EXISTS posts (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    author_id    BIGINT        NOT NULL,
    caption      VARCHAR(2200) NOT NULL DEFAULT '',
    status       VARCHAR(10)   NOT NULL DEFAULT 'processing',
    aspect_ratio VARCHAR(10)   NOT NULL,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    CONSTRAINT posts_status_chk CHECK (status IN ('processing', 'published'))
);

CREATE INDEX IF NOT EXISTS posts_author_idx ON posts (author_id, created_at DESC);

CREATE INDEX IF NOT EXISTS posts_feed_idx   ON posts (created_at DESC) WHERE status = 'published';

CREATE TABLE IF NOT EXISTS post_images (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id    BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    image_url  VARCHAR(255) NOT NULL,
    position   INTEGER      NOT NULL CHECK (position >= 0),
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    UNIQUE (post_id, position)
);

CREATE TABLE IF NOT EXISTS post_likes (
    user_id    BIGINT      NOT NULL,
    post_id    BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);

CREATE INDEX IF NOT EXISTS post_likes_post_idx ON post_likes (post_id);

CREATE TABLE IF NOT EXISTS reposts (
    user_id    BIGINT      NOT NULL,
    post_id    BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);

CREATE INDEX IF NOT EXISTS reposts_post_idx ON reposts (post_id);

CREATE TABLE IF NOT EXISTS post_favorites (
    user_id    BIGINT      NOT NULL,
    post_id    BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);

CREATE TABLE IF NOT EXISTS hidden_posts (
    user_id    BIGINT      NOT NULL,
    post_id    BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, post_id)
);

CREATE TABLE IF NOT EXISTS comments (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id           BIGINT       NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    author_id         BIGINT       NOT NULL,
    parent_comment_id BIGINT       REFERENCES comments (id) ON DELETE CASCADE,
    text              VARCHAR(500) NOT NULL,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS comments_post_idx   ON comments (post_id, created_at);

CREATE INDEX IF NOT EXISTS comments_parent_idx ON comments (parent_comment_id);

CREATE INDEX IF NOT EXISTS comments_author_idx ON comments (author_id);

CREATE TABLE IF NOT EXISTS comment_likes (
    user_id    BIGINT      NOT NULL,
    comment_id BIGINT      NOT NULL REFERENCES comments (id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (user_id, comment_id)
);

CREATE INDEX IF NOT EXISTS comment_likes_comment_idx ON comment_likes (comment_id);

CREATE TABLE IF NOT EXISTS post_reports (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id     BIGINT      NOT NULL REFERENCES posts (id) ON DELETE CASCADE,
    reporter_id BIGINT      NOT NULL,
    description TEXT        NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (post_id, reporter_id)
);

CREATE TABLE IF NOT EXISTS user_replicas (
    user_id       BIGINT       PRIMARY KEY,
    username      VARCHAR(30)  NOT NULL,
    display_name  VARCHAR(255) NOT NULL,
    avatar_url    VARCHAR(255) NOT NULL DEFAULT '',
    role          VARCHAR(10)  NOT NULL,
    status        VARCHAR(20)  NOT NULL,
    token_version INTEGER      NOT NULL,
    last_event_id BIGINT       NOT NULL
);

CREATE INDEX IF NOT EXISTS user_replicas_username_idx ON user_replicas (lower(username));

CREATE TABLE IF NOT EXISTS follow_replicas (
    follower_id   BIGINT  NOT NULL,
    followee_id   BIGINT  NOT NULL,
    following     BOOLEAN NOT NULL,
    last_event_id BIGINT  NOT NULL,
    PRIMARY KEY (follower_id, followee_id)
);

CREATE TABLE IF NOT EXISTS outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key  VARCHAR(64) NOT NULL,
    payload      JSON        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS outbox_pending_idx ON outbox (id) WHERE published_at IS NULL;

-- База User Service (user_db). Таблицы — по services/ENDPOINTS.md: users, profiles,
-- follows, refresh_tokens, email_tokens, password_reset_tokens.
-- Исходник: social_network_db/init/01_schema.sql, без изменений в этих таблицах.
-- Сверху добавлены user_post_counts (счётчик постов из событий Content Service)
-- и outbox (исходящие события для RabbitMQ).

CREATE TABLE IF NOT EXISTS users (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(255) NOT NULL,
    username      VARCHAR(30)  NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(10)  NOT NULL DEFAULT 'user',
    status        VARCHAR(20)  NOT NULL DEFAULT 'pending',
    token_version INTEGER      NOT NULL DEFAULT 1,
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT users_id_username_uq UNIQUE (id, username),
    CONSTRAINT users_role_chk   CHECK (role IN ('user', 'moderator', 'admin')),
    CONSTRAINT users_status_chk CHECK (status IN ('pending', 'active', 'blocked', 'deleted'))
);

CREATE UNIQUE INDEX IF NOT EXISTS users_email_uq    ON users (lower(email));

CREATE UNIQUE INDEX IF NOT EXISTS users_username_uq ON users (lower(username));

CREATE TABLE IF NOT EXISTS profiles (
    user_id        BIGINT       PRIMARY KEY,
    username       VARCHAR(30)  NOT NULL,
    display_name   VARCHAR(255) NOT NULL,
    bio            VARCHAR(150) NOT NULL DEFAULT '',
    avatar_url     VARCHAR(255) NOT NULL DEFAULT '',
    follower_count INTEGER NOT NULL DEFAULT 0 CHECK (follower_count >= 0),
    followee_count INTEGER NOT NULL DEFAULT 0 CHECK (followee_count >= 0),
    CONSTRAINT profiles_user_fk FOREIGN KEY (user_id, username)
        REFERENCES users (id, username) ON UPDATE CASCADE ON DELETE CASCADE
);

CREATE UNIQUE INDEX IF NOT EXISTS profiles_username_uq ON profiles (lower(username));

CREATE TABLE IF NOT EXISTS follows (
    follower_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    followee_id BIGINT      NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT now(),
    PRIMARY KEY (follower_id, followee_id),
    CONSTRAINT follows_no_self_chk CHECK (follower_id <> followee_id)
);

CREATE INDEX IF NOT EXISTS follows_followee_idx ON follows (followee_id);

CREATE TABLE IF NOT EXISTS refresh_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    version    INTEGER      NOT NULL DEFAULT 1,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ  NOT NULL,
    revoked_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS refresh_tokens_user_idx ON refresh_tokens (user_id);

CREATE TABLE IF NOT EXISTS email_tokens (
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    purpose    VARCHAR(6)   NOT NULL,
    token_hash VARCHAR(255) NOT NULL,
    attempts   INTEGER      NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ  NOT NULL,
    used_at    TIMESTAMPTZ,
    PRIMARY KEY (user_id, purpose),
    CONSTRAINT email_tokens_purpose_chk CHECK (purpose IN ('verify', 'reset'))
);

CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT       NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    token_hash VARCHAR(255) NOT NULL UNIQUE,
    created_at TIMESTAMPTZ  NOT NULL DEFAULT now(),
    expires_at TIMESTAMPTZ  NOT NULL,
    used_at    TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS password_reset_tokens_user_idx ON password_reset_tokens (user_id);

CREATE TABLE IF NOT EXISTS user_post_counts (
    user_id       BIGINT  PRIMARY KEY REFERENCES users (id) ON DELETE CASCADE,
    posts_count   INTEGER NOT NULL DEFAULT 0,
    last_event_id BIGINT  NOT NULL DEFAULT 0
);

CREATE TABLE IF NOT EXISTS outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    routing_key  VARCHAR(64) NOT NULL,
    payload      JSON        NOT NULL,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    published_at TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS outbox_pending_idx ON outbox (id) WHERE published_at IS NULL;

-- База Recommendation Service (recommendation_db). Таблицы — по services/ENDPOINTS.md:
-- post_text_embeddings, post_image_embeddings. Сами векторы лежат в Qdrant.
-- Исходник: social_network_db/init/01_schema.sql. posts и post_images живут в
-- базе Content Service, поэтому post_id / image_id — без внешнего ключа.

CREATE TABLE IF NOT EXISTS post_text_embeddings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    post_id         BIGINT       NOT NULL,
    qdrant_point_id UUID         NOT NULL UNIQUE,
    model_version   VARCHAR(255) NOT NULL,
    UNIQUE (post_id, model_version)
);

CREATE TABLE IF NOT EXISTS post_image_embeddings (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    image_id        BIGINT       NOT NULL,
    qdrant_point_id UUID         NOT NULL UNIQUE,
    model_version   VARCHAR(255) NOT NULL,
    UNIQUE (image_id, model_version)
);
